function configure_spinner_path(spinnerDir)
%CONFIGURE_SPINNER_PATH Put only the current SpINNEr source directory first.

if ~isfolder(spinnerDir)
    error('SwapPilot:MissingSpINNeR', ...
        'The SpINNEr toolbox was not found at %s.', spinnerDir);
end

addpath(spinnerDir, '-begin');

requiredFiles = { ...
    'spinner', ...
    'ParseArgumentsFit', ...
    'Logistic_spinnerCV', ...
    'Logistic_spinnerCVlasso', ...
    'Logistic_spinnerCVnuclear', ...
    'spinnerCV', ...
    'LogisticSpinner', ...
    'spinnerRun'};

for fileIndex = 1:numel(requiredFiles)
    functionName = requiredFiles{fileIndex};
    resolvedPath = which(functionName);
    expectedPath = fullfile(spinnerDir, [functionName, '.m']);
    if ~strcmp(resolvedPath, expectedPath)
        error('SwapPilot:PathShadowing', ...
            '%s resolves to %s instead of %s.', ...
            functionName, resolvedPath, expectedPath);
    end
end
end
