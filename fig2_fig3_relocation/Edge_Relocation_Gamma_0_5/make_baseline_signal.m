function B = make_baseline_signal(p, signalStrength)
%MAKE_BASELINE_SIGNAL Reproduce the block-diagonal signal from the recent study.

if p < 32 || p ~= floor(p)
    error('SwapPilot:InvalidDimension', ...
        'The matrix dimension must be an integer of at least 32.');
end

B1 = signalStrength .* ones(5, 5);
B2 = -signalStrength .* ones(5, 5);
B3 = signalStrength .* ones(4, 4);
remainingSize = p - 32;

B = blkdiag( ...
    zeros(5, 5), ...
    B1, ...
    zeros(6, 6), ...
    B2, ...
    zeros(7, 7), ...
    B3, ...
    zeros(remainingSize, remainingSize));
end
