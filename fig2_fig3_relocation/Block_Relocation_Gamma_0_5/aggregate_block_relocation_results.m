function summaryFile = aggregate_block_relocation_results(nReplicatesToUse, resultsDir, outputDirectory)
%AGGREGATE_BLOCK_RELOCATION_RESULTS Write MAT/CSV numerical summaries only.

config = block_relocation_config();
if nargin < 3 || isempty(outputDirectory)
    outputDirectory = fullfile(config.simulationDir, 'recomputed_summaries');
end

if nargin >= 2 && ~isempty(resultsDir)
    config.resultsDir = resultsDir;
end
if nargin < 1 || isempty(nReplicatesToUse)
    nReplicatesToUse = config.nReplicates;
end
if ~isscalar(nReplicatesToUse) || nReplicatesToUse < 1 || ...
        nReplicatesToUse > config.nReplicates || ...
        nReplicatesToUse ~= floor(nReplicatesToUse)
    error('BlockRelocation:InvalidReplicateCount', ...
        'nReplicatesToUse must be an integer from 1 through %d.', ...
        config.nReplicates);
end

nBlocks = config.nBlockSettings;
nConditions = config.nConditions;
nReplicates = nReplicatesToUse;
nMethods = config.nMethods;
arraySize = [nBlocks, nConditions, nReplicates, nMethods];

ACC = nan(arraySize);
AUC = nan(arraySize);
Euclid = nan(arraySize);
bestLambdaN = nan(arraySize);
bestLambdaL = nan(arraySize);
estimateRank = nan(arraySize);
estimateFrobeniusNorm = nan(arraySize);
maxAbsCoefficient = nan(arraySize);
allZeroEstimate = false(arraySize);
zeroUpperEdgeCount = nan(arraySize);
responseMean = nan(nBlocks, nConditions, nReplicates);
meanProbability = nan(nBlocks, nConditions, nReplicates);
extremeProbabilityProportion = nan(nBlocks, nConditions, nReplicates);
trueRank = nan(nBlocks, nConditions, nReplicates);
trueFrobeniusNorm = nan(nBlocks, nConditions, nReplicates);
trueNuclearNorm = nan(nBlocks, nConditions, nReplicates);
trueL1Norm = nan(nBlocks, nConditions, nReplicates);
actualSwapProportions = nan(nBlocks, nConditions);
kGrids = nan(nBlocks, nConditions);
nonzeroUpperEdgeCounts = nan(nBlocks, 1);

for blockIndex = 1:nBlocks
    blockLabel = config.blockLabels{blockIndex};
    for replicateId = 1:nReplicates
        resultFile = fullfile(config.resultsDir, sprintf( ...
            'relocation_gamma0p5_blocks_%s_replicate_%02d.mat', blockLabel, replicateId));
        if ~isfile(resultFile)
            error('BlockRelocation:MissingResult', ...
                'Missing result: %s', resultFile);
        end
        loaded = load(resultFile, 'result');
        if ~isfield(loaded, 'result')
            error('BlockRelocation:InvalidCheckpoint', ...
                'The result structure is missing from %s.', resultFile);
        end
        result = loaded.result;
        validate_completed_result(result, config, blockIndex, ...
            replicateId, resultFile);

        ACC(blockIndex, :, replicateId, :) = reshape( ...
            result.ACC, [1, nConditions, 1, nMethods]);
        AUC(blockIndex, :, replicateId, :) = reshape( ...
            result.AUC, [1, nConditions, 1, nMethods]);
        Euclid(blockIndex, :, replicateId, :) = reshape( ...
            result.Euclid, [1, nConditions, 1, nMethods]);
        bestLambdaN(blockIndex, :, replicateId, :) = reshape( ...
            result.bestLambdaN, [1, nConditions, 1, nMethods]);
        bestLambdaL(blockIndex, :, replicateId, :) = reshape( ...
            result.bestLambdaL, [1, nConditions, 1, nMethods]);
        estimateRank(blockIndex, :, replicateId, :) = reshape( ...
            result.estimateRank, [1, nConditions, 1, nMethods]);
        estimateFrobeniusNorm(blockIndex, :, replicateId, :) = reshape( ...
            result.estimateFrobeniusNorm, ...
            [1, nConditions, 1, nMethods]);
        maxAbsCoefficient(blockIndex, :, replicateId, :) = reshape( ...
            result.maxAbsCoefficient, [1, nConditions, 1, nMethods]);
        allZeroEstimate(blockIndex, :, replicateId, :) = reshape( ...
            result.allZeroEstimate, [1, nConditions, 1, nMethods]);
        zeroUpperEdgeCount(blockIndex, :, replicateId, :) = reshape( ...
            result.zeroUpperEdgeCount, [1, nConditions, 1, nMethods]);
        responseMean(blockIndex, :, replicateId) = result.responseMean;
        meanProbability(blockIndex, :, replicateId) = result.meanProbability;
        extremeProbabilityProportion(blockIndex, :, replicateId) = ...
            result.extremeProbabilityProportion;
        trueRank(blockIndex, :, replicateId) = result.trueRank;
        trueFrobeniusNorm(blockIndex, :, replicateId) = ...
            result.trueFrobeniusNorm;
        trueNuclearNorm(blockIndex, :, replicateId) = result.trueNuclearNorm;
        trueL1Norm(blockIndex, :, replicateId) = result.trueL1Norm;

        if replicateId == 1
            actualSwapProportions(blockIndex, :) = result.swapProportions;
            kGrids(blockIndex, :) = result.kGrid;
            nonzeroUpperEdgeCounts(blockIndex) = ...
                result.signalInfo.nonzeroUpperEdgeCount;
        elseif ~isequal(result.swapProportions, ...
                actualSwapProportions(blockIndex, :)) || ...
                ~isequal(result.kGrid, kGrids(blockIndex, :))
            error('BlockRelocation:InconsistentSwapGrid', ...
                'Swap grid differs within block setting %s.', blockLabel);
        end
    end
end

longTable = make_long_table(config, nReplicates, ACC, AUC, Euclid, bestLambdaN, ...
    bestLambdaL, estimateRank, estimateFrobeniusNorm, maxAbsCoefficient, ...
    allZeroEstimate, zeroUpperEdgeCount, responseMean, meanProbability, ...
    extremeProbabilityProportion, trueRank, trueFrobeniusNorm, ...
    trueNuclearNorm, trueL1Norm, actualSwapProportions, kGrids, ...
    nonzeroUpperEdgeCounts);
summaryTable = make_summary_table(config, nReplicates, ACC, AUC, Euclid, ...
    estimateRank, allZeroEstimate, zeroUpperEdgeCount, responseMean, ...
    extremeProbabilityProportion, trueRank, trueFrobeniusNorm, ...
    actualSwapProportions, kGrids, nonzeroUpperEdgeCounts);

% Delivery output routing; supplied input checkpoints stay unchanged.
config.resultsDir = outputDirectory;
if ~isfolder(config.resultsDir)
    mkdir(config.resultsDir);
end
fileStem = sprintf('block_relocation_gamma0p5_summary_rep%02d', nReplicates);
summaryFile = fullfile(config.resultsDir, [fileStem, '.mat']);
longCsvFile = fullfile(config.resultsDir, [fileStem, '_long.csv']);
methodsCsvFile = fullfile(config.resultsDir, [fileStem, '_methods.csv']);
save(summaryFile, 'config', 'ACC', 'AUC', 'Euclid', 'bestLambdaN', 'bestLambdaL', ...
    'estimateRank', 'estimateFrobeniusNorm', 'maxAbsCoefficient', ...
    'allZeroEstimate', 'zeroUpperEdgeCount', 'responseMean', ...
    'meanProbability', 'extremeProbabilityProportion', 'trueRank', ...
    'trueFrobeniusNorm', 'trueNuclearNorm', 'trueL1Norm', ...
    'actualSwapProportions', 'kGrids', 'nonzeroUpperEdgeCounts', ...
    'longTable', 'summaryTable', 'nReplicates', '-v7.3');
writetable(longTable, longCsvFile);
writetable(summaryTable, methodsCsvFile);

fprintf('Numerical summaries written to:\n');
fprintf('  %s\n', summaryFile);
fprintf('  %s\n', longCsvFile);
fprintf('  %s\n', methodsCsvFile);
end

function validate_completed_result(result, config, blockIndex, ...
        replicateId, resultFile)
requiredFields = {'schemaVersion', 'configSignature', 'blockIndex', ...
    'blockSizes', 'blockLabel', 'replicateId', 'coefficientMagnitude', ...
    'signalInfo', 'kGrid', 'swapProportions', 'methodNames', 'ACC', ...
    'AUC', 'Euclid', 'Probs', 'betaHat', 'responses', 'predictionMetricScope', ...
    'bestLambdaN', 'bestLambdaL', 'estimateRank', ...
    'estimateFrobeniusNorm', 'maxAbsCoefficient', 'allZeroEstimate', ...
    'zeroUpperEdgeCount', 'responseMean', 'meanProbability', ...
    'extremeProbabilityProportion', 'trueRank', 'trueFrobeniusNorm', ...
    'trueNuclearNorm', 'trueL1Norm', 'completed'};
for fieldIndex = 1:numel(requiredFields)
    if ~isfield(result, requiredFields{fieldIndex})
        error('BlockRelocation:InvalidCheckpoint', ...
            'Field %s is missing from %s.', ...
            requiredFields{fieldIndex}, resultFile);
    end
end

isValid = ...
    result.schemaVersion == config.schemaVersion && ...
    strcmp(result.configSignature, config.signature) && ...
    result.blockIndex == blockIndex && ...
    isequal(result.blockSizes, config.blockSizeGrid(blockIndex, :)) && ...
    strcmp(result.blockLabel, config.blockLabels{blockIndex}) && ...
    result.replicateId == replicateId && ...
    result.coefficientMagnitude == config.coefficientMagnitude && ...
    result.signalInfo.coefficientMagnitude == config.coefficientMagnitude && ...
    strcmp(result.predictionMetricScope, config.predictionMetricScope) && ...
    isequal(result.methodNames, config.methodNames) && ...
    all(result.completed(:)) && ...
    all(isfinite(result.ACC(:))) && ...
    all(isfinite(result.estimateRank(:))) && ...
    all(isfinite(result.zeroUpperEdgeCount(:)));
if ~isValid
    error('BlockRelocation:IncompleteResult', ...
        'Result is incomplete or incompatible: %s', resultFile);
end
validate_relocation_saved_metrics(result, config);
end

function longTable = make_long_table(config, nReplicates, ACC, AUC, Euclid, ...
        bestLambdaN, bestLambdaL, estimateRank, estimateFrobeniusNorm, ...
        maxAbsCoefficient, allZeroEstimate, zeroUpperEdgeCount, ...
        responseMean, meanProbability, extremeProbabilityProportion, ...
        trueRank, trueFrobeniusNorm, trueNuclearNorm, trueL1Norm, ...
        actualSwapProportions, kGrids, nonzeroUpperEdgeCounts)
nRows = config.nBlockSettings * config.nConditions * nReplicates * ...
    config.nMethods;
blockLabelColumn = cell(nRows, 1);
block1Column = zeros(nRows, 1);
block2Column = zeros(nRows, 1);
block3Column = zeros(nRows, 1);
coefficientColumn = repmat(config.coefficientMagnitude, nRows, 1);
nonzeroEdgeColumn = zeros(nRows, 1);
replicateColumn = zeros(nRows, 1);
kColumn = zeros(nRows, 1);
targetSwapColumn = zeros(nRows, 1);
actualSwapColumn = zeros(nRows, 1);
methodColumn = cell(nRows, 1);
accColumn = zeros(nRows, 1);
aucColumn = nan(nRows, 1);
euclidColumn = nan(nRows, 1);
predictionAvailableColumn = false(nRows, 1);
lambdaNColumn = nan(nRows, 1);
lambdaLColumn = nan(nRows, 1);
estimateRankColumn = zeros(nRows, 1);
estimateFrobeniusColumn = zeros(nRows, 1);
maxAbsColumn = zeros(nRows, 1);
allZeroColumn = false(nRows, 1);
zeroUpperColumn = zeros(nRows, 1);
responseMeanColumn = zeros(nRows, 1);
meanProbabilityColumn = zeros(nRows, 1);
extremeProbabilityColumn = zeros(nRows, 1);
trueRankColumn = zeros(nRows, 1);
trueFrobeniusColumn = zeros(nRows, 1);
trueNuclearColumn = zeros(nRows, 1);
trueL1Column = zeros(nRows, 1);

rowIndex = 0;
for blockIndex = 1:config.nBlockSettings
    for conditionIndex = 1:config.nConditions
        for replicateId = 1:nReplicates
            for methodIndex = 1:config.nMethods
                rowIndex = rowIndex + 1;
                blockLabelColumn{rowIndex} = config.blockLabels{blockIndex};
                block1Column(rowIndex) = config.blockSizeGrid(blockIndex, 1);
                block2Column(rowIndex) = config.blockSizeGrid(blockIndex, 2);
                block3Column(rowIndex) = config.blockSizeGrid(blockIndex, 3);
                nonzeroEdgeColumn(rowIndex) = ...
                    nonzeroUpperEdgeCounts(blockIndex);
                replicateColumn(rowIndex) = replicateId;
                kColumn(rowIndex) = kGrids(blockIndex, conditionIndex);
                targetSwapColumn(rowIndex) = ...
                    config.swapProportionTargets(conditionIndex);
                actualSwapColumn(rowIndex) = ...
                    actualSwapProportions(blockIndex, conditionIndex);
                methodColumn{rowIndex} = config.methodNames{methodIndex};
                accColumn(rowIndex) = ...
                    ACC(blockIndex, conditionIndex, replicateId, methodIndex);
                aucColumn(rowIndex) = ...
                    AUC(blockIndex, conditionIndex, replicateId, methodIndex);
                euclidColumn(rowIndex) = ...
                    Euclid(blockIndex, conditionIndex, replicateId, methodIndex);
                predictionAvailableColumn(rowIndex) = ...
                    ismember(methodIndex, config.predictionMethodIndices);
                lambdaNColumn(rowIndex) = bestLambdaN( ...
                    blockIndex, conditionIndex, replicateId, methodIndex);
                lambdaLColumn(rowIndex) = bestLambdaL( ...
                    blockIndex, conditionIndex, replicateId, methodIndex);
                estimateRankColumn(rowIndex) = estimateRank( ...
                    blockIndex, conditionIndex, replicateId, methodIndex);
                estimateFrobeniusColumn(rowIndex) = estimateFrobeniusNorm( ...
                    blockIndex, conditionIndex, replicateId, methodIndex);
                maxAbsColumn(rowIndex) = maxAbsCoefficient( ...
                    blockIndex, conditionIndex, replicateId, methodIndex);
                allZeroColumn(rowIndex) = allZeroEstimate( ...
                    blockIndex, conditionIndex, replicateId, methodIndex);
                zeroUpperColumn(rowIndex) = zeroUpperEdgeCount( ...
                    blockIndex, conditionIndex, replicateId, methodIndex);
                responseMeanColumn(rowIndex) = ...
                    responseMean(blockIndex, conditionIndex, replicateId);
                meanProbabilityColumn(rowIndex) = ...
                    meanProbability(blockIndex, conditionIndex, replicateId);
                extremeProbabilityColumn(rowIndex) = ...
                    extremeProbabilityProportion( ...
                    blockIndex, conditionIndex, replicateId);
                trueRankColumn(rowIndex) = ...
                    trueRank(blockIndex, conditionIndex, replicateId);
                trueFrobeniusColumn(rowIndex) = ...
                    trueFrobeniusNorm(blockIndex, conditionIndex, replicateId);
                trueNuclearColumn(rowIndex) = ...
                    trueNuclearNorm(blockIndex, conditionIndex, replicateId);
                trueL1Column(rowIndex) = ...
                    trueL1Norm(blockIndex, conditionIndex, replicateId);
            end
        end
    end
end

longTable = table(blockLabelColumn, block1Column, block2Column, ...
    block3Column, coefficientColumn, nonzeroEdgeColumn, replicateColumn, ...
    kColumn, targetSwapColumn, actualSwapColumn, methodColumn, accColumn, ...
    aucColumn, euclidColumn, predictionAvailableColumn, ...
    lambdaNColumn, lambdaLColumn, estimateRankColumn, ...
    estimateFrobeniusColumn, maxAbsColumn, allZeroColumn, zeroUpperColumn, ...
    responseMeanColumn, meanProbabilityColumn, extremeProbabilityColumn, ...
    trueRankColumn, trueFrobeniusColumn, trueNuclearColumn, trueL1Column, ...
    'VariableNames', {'BlockLabel', 'Block1Size', 'Block2Size', ...
    'Block3Size', 'CoefficientMagnitude', 'NonzeroUpperEdgeCount', ...
    'Replicate', 'K', 'TargetSwapProportion', 'ActualSwapProportion', ...
    'Method', 'ACC', 'AUC', 'Euclid', 'PredictionMetricsAvailable', ...
    'BestLambdaN', 'BestLambdaL', 'EstimateRank', ...
    'EstimateFrobeniusNorm', 'MaxAbsCoefficient', 'AllZeroEstimate', ...
    'ZeroUpperEdgeCount', 'ResponseMean', 'MeanProbability', ...
    'ExtremeProbabilityProportion', 'TrueRank', 'TrueFrobeniusNorm', ...
    'TrueNuclearNorm', 'TrueL1Norm'});
end

function summaryTable = make_summary_table(config, nReplicates, ACC, AUC, Euclid, ...
        estimateRank, allZeroEstimate, zeroUpperEdgeCount, responseMean, ...
        extremeProbabilityProportion, trueRank, trueFrobeniusNorm, ...
        actualSwapProportions, kGrids, nonzeroUpperEdgeCounts)
nRows = config.nBlockSettings * config.nConditions * config.nMethods;
blockLabelColumn = cell(nRows, 1);
block1Column = zeros(nRows, 1);
block2Column = zeros(nRows, 1);
block3Column = zeros(nRows, 1);
coefficientColumn = repmat(config.coefficientMagnitude, nRows, 1);
nonzeroEdgeColumn = zeros(nRows, 1);
kColumn = zeros(nRows, 1);
targetSwapColumn = zeros(nRows, 1);
actualSwapColumn = zeros(nRows, 1);
methodColumn = cell(nRows, 1);
nReplicateColumn = repmat(nReplicates, nRows, 1);
meanACCColumn = zeros(nRows, 1);
meanAUCColumn = nan(nRows, 1);
semAUCColumn = nan(nRows, 1);
twoSEMAUCColumn = nan(nRows, 1);
meanEuclidColumn = nan(nRows, 1);
semEuclidColumn = nan(nRows, 1);
twoSEMEuclidColumn = nan(nRows, 1);
nPredictionReplicatesColumn = zeros(nRows, 1);
semACCColumn = zeros(nRows, 1);
twoSEMColumn = zeros(nRows, 1);
meanEstimateRankColumn = zeros(nRows, 1);
allZeroCountColumn = zeros(nRows, 1);
allZeroFrequencyColumn = zeros(nRows, 1);
meanZeroUpperColumn = zeros(nRows, 1);
meanResponseColumn = zeros(nRows, 1);
meanExtremeProbabilityColumn = zeros(nRows, 1);
meanTrueRankColumn = zeros(nRows, 1);
meanTrueFrobeniusColumn = zeros(nRows, 1);

rowIndex = 0;
for blockIndex = 1:config.nBlockSettings
    for conditionIndex = 1:config.nConditions
        for methodIndex = 1:config.nMethods
            rowIndex = rowIndex + 1;
            currentACC = reshape(ACC(blockIndex, conditionIndex, :, ...
                methodIndex), [nReplicates, 1]);
            currentEstimateRank = reshape(estimateRank(blockIndex, ...
                conditionIndex, :, methodIndex), [nReplicates, 1]);
            currentAllZero = reshape(allZeroEstimate(blockIndex, ...
                conditionIndex, :, methodIndex), [nReplicates, 1]);
            currentZeroUpper = reshape(zeroUpperEdgeCount(blockIndex, ...
                conditionIndex, :, methodIndex), [nReplicates, 1]);

            blockLabelColumn{rowIndex} = config.blockLabels{blockIndex};
            block1Column(rowIndex) = config.blockSizeGrid(blockIndex, 1);
            block2Column(rowIndex) = config.blockSizeGrid(blockIndex, 2);
            block3Column(rowIndex) = config.blockSizeGrid(blockIndex, 3);
            nonzeroEdgeColumn(rowIndex) = ...
                nonzeroUpperEdgeCounts(blockIndex);
            kColumn(rowIndex) = kGrids(blockIndex, conditionIndex);
            targetSwapColumn(rowIndex) = ...
                config.swapProportionTargets(conditionIndex);
            actualSwapColumn(rowIndex) = ...
                actualSwapProportions(blockIndex, conditionIndex);
            methodColumn{rowIndex} = config.methodNames{methodIndex};
            meanACCColumn(rowIndex) = mean(currentACC);
            if ismember(methodIndex, config.predictionMethodIndices)
                currentAUC = reshape(AUC(blockIndex, conditionIndex, :, ...
                    methodIndex), [nReplicates, 1]);
                currentEuclid = reshape(Euclid(blockIndex, conditionIndex, :, ...
                    methodIndex), [nReplicates, 1]);
                meanAUCColumn(rowIndex) = mean(currentAUC);
                semAUCColumn(rowIndex) = std(currentAUC) / sqrt(nReplicates);
                twoSEMAUCColumn(rowIndex) = 2 * semAUCColumn(rowIndex);
                meanEuclidColumn(rowIndex) = mean(currentEuclid);
                semEuclidColumn(rowIndex) = std(currentEuclid) / sqrt(nReplicates);
                twoSEMEuclidColumn(rowIndex) = 2 * semEuclidColumn(rowIndex);
                nPredictionReplicatesColumn(rowIndex) = nReplicates;
            end
            semACCColumn(rowIndex) = std(currentACC) / sqrt(nReplicates);
            twoSEMColumn(rowIndex) = 2 * semACCColumn(rowIndex);
            meanEstimateRankColumn(rowIndex) = mean(currentEstimateRank);
            allZeroCountColumn(rowIndex) = sum(currentAllZero);
            allZeroFrequencyColumn(rowIndex) = ...
                allZeroCountColumn(rowIndex) / nReplicates;
            meanZeroUpperColumn(rowIndex) = mean(currentZeroUpper);
            meanResponseColumn(rowIndex) = mean(reshape( ...
                responseMean(blockIndex, conditionIndex, :), ...
                [nReplicates, 1]));
            meanExtremeProbabilityColumn(rowIndex) = mean(reshape( ...
                extremeProbabilityProportion(blockIndex, conditionIndex, :), ...
                [nReplicates, 1]));
            meanTrueRankColumn(rowIndex) = mean(reshape( ...
                trueRank(blockIndex, conditionIndex, :), ...
                [nReplicates, 1]));
            meanTrueFrobeniusColumn(rowIndex) = mean(reshape( ...
                trueFrobeniusNorm(blockIndex, conditionIndex, :), ...
                [nReplicates, 1]));
        end
    end
end

summaryTable = table(blockLabelColumn, block1Column, block2Column, ...
    block3Column, coefficientColumn, nonzeroEdgeColumn, kColumn, ...
    targetSwapColumn, actualSwapColumn, methodColumn, nReplicateColumn, ...
    meanACCColumn, semACCColumn, twoSEMColumn, ...
    meanAUCColumn, semAUCColumn, twoSEMAUCColumn, ...
    meanEuclidColumn, semEuclidColumn, twoSEMEuclidColumn, ...
    nPredictionReplicatesColumn, meanEstimateRankColumn, ...
    allZeroCountColumn, allZeroFrequencyColumn, meanZeroUpperColumn, ...
    meanResponseColumn, meanExtremeProbabilityColumn, meanTrueRankColumn, ...
    meanTrueFrobeniusColumn, 'VariableNames', ...
    {'BlockLabel', 'Block1Size', 'Block2Size', 'Block3Size', ...
    'CoefficientMagnitude', 'NonzeroUpperEdgeCount', 'K', ...
    'TargetSwapProportion', 'ActualSwapProportion', 'Method', ...
    'NReplicates', 'MeanACC', 'SEM', 'TwoSEM', ...
    'MeanAUC', 'SEMAUC', 'TwoSEMAUC', ...
    'MeanEuclid', 'SEMEuclid', 'TwoSEMEuclid', ...
    'NPredictionReplicates', 'MeanEstimateRank', ...
    'AllZeroCount', 'AllZeroFrequency', 'MeanZeroUpperEdgeCount', ...
    'MeanResponse', 'MeanExtremeProbabilityProportion', 'MeanTrueRank', ...
    'MeanTrueFrobeniusNorm'});
end
