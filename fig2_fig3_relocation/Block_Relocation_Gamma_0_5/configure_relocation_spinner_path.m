function configure_relocation_spinner_path(spinnerDir)
%CONFIGURE_RELOCATION_SPINNER_PATH Put the intended SpINNEr source first on path.

if ~isfolder(spinnerDir)
    error('BlockRelocation:MissingSpINNeR', ...
        'The SpINNEr toolbox was not found at %s.', spinnerDir);
end
addpath(spinnerDir, '-begin');

requiredFunctions = { ...
    'spinner', ...
    'ParseArgumentsFit', ...
    'Logistic_spinnerCV', ...
    'Logistic_spinnerCVlasso', ...
    'Logistic_spinnerCVnuclear', ...
    'spinnerCV', ...
    'LogisticSpinner', ...
    'spinnerRun'};
for functionIndex = 1:numel(requiredFunctions)
    functionName = requiredFunctions{functionIndex};
    resolvedPath = which(functionName);
    expectedPath = fullfile(spinnerDir, [functionName, '.m']);
    if ~strcmp(resolvedPath, expectedPath)
        error('BlockRelocation:PathShadowing', ...
            '%s resolves to %s instead of %s.', ...
            functionName, resolvedPath, expectedPath);
    end
end

% Catch an older cluster source before launching any expensive fits.
logisticFunctions = {'Logistic_spinnerCV', 'Logistic_spinnerCVlasso', ...
    'Logistic_spinnerCVnuclear'};
for functionIndex = 1:numel(logisticFunctions)
    source = fileread(fullfile(spinnerDir, [logisticFunctions{functionIndex}, '.m']));
    for field = {'AUC', 'Euclid', 'Probs'}
        pattern = ['out\s*\.\s*', field{1}, '\s*='];
        if isempty(regexp(source, pattern, 'once'))
            error('BlockRelocation:MissingNativeMetricSource', ...
                '%s does not output %s. Check the read-only SpINNEr source version.', ...
                logisticFunctions{functionIndex}, field{1});
        end
    end
end
end
