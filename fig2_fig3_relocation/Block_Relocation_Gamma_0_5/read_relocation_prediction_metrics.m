function [auc, euclid, probs] = read_relocation_prediction_metrics(estimate, y)
%READ_RELOCATION_PREDICTION_METRICS Read native logistic output without refitting.

requiredFields = {'AUC', 'Euclid', 'Probs'};
for index = 1:numel(requiredFields)
    if ~isfield(estimate, requiredFields{index})
        error('BlockRelocation:MissingPredictionMetric', ...
            'SpINNEr output is missing %s. Check the cluster source version.', ...
            requiredFields{index});
    end
end
auc = estimate.AUC;
euclid = estimate.Euclid;
probs = estimate.Probs;
if ~isnumeric(probs) || ~isequal(size(probs), size(y)) || ...
        any(~isfinite(probs(:))) || any(probs(:) < 0 | probs(:) > 1) || ...
        ~isnumeric(auc) || ~isscalar(auc) || ~isfinite(auc) || ...
        auc < 0 || auc > 1 || ...
        ~isnumeric(euclid) || ~isscalar(euclid) || ~isfinite(euclid) || ...
        euclid < 0 || abs(euclid - norm(y - probs)) > 1e-10 * max(1, euclid)
    error('BlockRelocation:InvalidPredictionMetric', ...
        'Native AUC, Euclid, or Probs are invalid or inconsistent.');
end
end
