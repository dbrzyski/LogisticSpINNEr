function validate_relocation_generated_inputs(config, blockSizes, BBaseline, signalInfo, ...
        BTrue, swapInfo, kGrid, A, responses, probabilities)
upperMask = triu(true(config.p), 1);
baselineSupport = upperMask & (BBaseline ~= 0);
baselineZero = upperMask & (BBaseline == 0);
baselineNorm = norm(BBaseline, 'fro');

if signalInfo.rank ~= 3 || ...
        ~isequal(signalInfo.blockSizes, blockSizes) || ...
        signalInfo.coefficientMagnitude ~= config.coefficientMagnitude || ...
        nnz(baselineSupport) ~= signalInfo.nonzeroUpperEdgeCount || ...
        any(~ismember(BBaseline(:), config.coefficientMagnitude * [-1, 0, 1]))
    error('BlockRelocation:InvalidBaselineSignal', ...
        'The baseline for the requested block setting is invalid.');
end
if ~isequal(swapInfo.kGrid, kGrid) || ...
        ~isequal(swapInfo.swapProportions, ...
        kGrid ./ signalInfo.nonzeroUpperEdgeCount)
    error('BlockRelocation:InvalidSwapGrid', ...
        'Generated swap counts or proportions are incorrect.');
end

for conditionIndex = 1:numel(kGrid)
    currentSignal = BTrue(:, :, conditionIndex);
    currentSupport = upperMask & (currentSignal ~= 0);
    k = kGrid(conditionIndex);
    if norm(currentSignal - currentSignal.', 'fro') > 1e-12 || ...
            nnz(currentSupport) ~= signalInfo.nonzeroUpperEdgeCount || ...
            abs(norm(currentSignal, 'fro') - baselineNorm) > 1e-12 || ...
            nnz(baselineSupport & ~currentSupport) ~= k || ...
            nnz(baselineZero & currentSupport) ~= k || ...
            ~isequal(diag(currentSignal), diag(BBaseline)) || ...
            any(~ismember(currentSignal(:), ...
            config.coefficientMagnitude * [-1, 0, 1]))
        error('BlockRelocation:InvalidSwappedSignal', ...
            'The swapped signal for k=%d failed validation.', k);
    end
end

if ~isequal(size(A), [config.p, config.p, config.n]) || ...
        any(~isfinite(A(:)))
    error('BlockRelocation:InvalidDesign', ...
        'The generated design has invalid dimensions or values.');
end
for observationIndex = 1:config.n
    currentA = A(:, :, observationIndex);
    if norm(currentA - currentA.', 'fro') > 1e-12 || ...
            any(diag(currentA) ~= 0)
        error('BlockRelocation:InvalidDesign', ...
            'Each design matrix must be symmetric with zero diagonal.');
    end
end
if ~isequal(size(responses), [config.n, config.nConditions]) || ...
        ~all(ismember(responses(:), [0, 1])) || ...
        ~isequal(size(probabilities), size(responses)) || ...
        any(~isfinite(probabilities(:))) || ...
        any(probabilities(:) < 0 | probabilities(:) > 1)
    error('BlockRelocation:InvalidResponse', ...
        'Generated responses or probabilities are invalid.');
end
end

